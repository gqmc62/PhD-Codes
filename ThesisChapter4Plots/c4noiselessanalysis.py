import pickle
import numpy as np
from matplotlib import pyplot as plt

with open(r'C:\Users\gqmc62\OneDrive - Durham University\Documents\PhD\Codes\ThesisChapter4Plots\Data\NoiselessCircularPupilSlopes.pkl','rb') as file:
  data = pickle.load(file)

Ig_SLOPE = data['Ig_SLOPE']
SHWFS_SLOPE = data['SHWFS_SLOPE']
print(Ig_SLOPE.shape)
ERROR = np.nanstd(Ig_SLOPE - SHWFS_SLOPE,axis=(-1,-2))
ERROR[ERROR==0] = np.nan

with open('Ultimate_input.pkl','rb') as file2:
  data2 = pickle.load(file2)

r0 = data2['r0']
dor0 = data2['dor0']
Rytov = data2['Rytov']
H_HA = data2['H_HA']

for i in np.arange(4):
  plt.plot(ERROR[i].flatten(),label='r0={}'.format(r0[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.plot(ERROR[:,i].flatten(),label='dor0={}'.format(dor0[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.plot(ERROR[:,:,i].flatten(),label='Rytov={}'.format(Rytov[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.plot(ERROR[:,:,:,i].flatten(),label='H_HA={}'.format(H_HA[i]),ls='-',marker='o')
plt.legend()
plt.show()

plt.errorbar(np.arange(4),np.nanmean(ERROR,axis=(1,2,3)),yerr=np.nanstd(ERROR,axis=(1,2,3)),label='r0',ls='-',marker='o',capsize=5)
plt.errorbar(np.arange(4),np.nanmean(ERROR,axis=(0,2,3)),yerr=np.nanstd(ERROR,axis=(0,2,3)),label='dor0',ls='-',marker='o',capsize=5)
plt.errorbar(np.arange(4),np.nanmean(ERROR,axis=(0,1,3)),yerr=np.nanstd(ERROR,axis=(0,1,3)),label='Rytov',ls='-',marker='o',capsize=5)
plt.errorbar(np.arange(4),np.nanmean(ERROR,axis=(0,1,2)),yerr=np.nanstd(ERROR,axis=(0,1,2)),label='H_HA',ls='-',marker='o',capsize=5)

ERROR1 = np.zeros_like(ERROR)
ERROR1std = np.zeros_like(ERROR)
for ii in np.arange(4):
  for jj in np.arange(4):
    for kk in np.arange(4):
      for ll in np.arange(4):
        ERROR1[ii,jj,kk,ll] = ERROR[ii,jj,kk,ll] - np.nanmean(ERROR,axis=(0,2,3))[jj]
        ERROR1std[ii,jj,kk,ll] = np.nanstd(ERROR,axis=(0,2,3))[jj]
dor0_contribution = np.nanmean(ERROR,axis=(0,2,3))
dor0_contribution_s = np.nanstd(ERROR,axis=(0,2,3))

for i in np.arange(4):
  plt.errorbar(np.arange(64),ERROR1[i].flatten(),yerr=ERROR1std[i].flatten(),label='r0={}'.format(r0[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.errorbar(np.arange(64),ERROR1[:,i].flatten(),yerr=ERROR1std[:,i].flatten(),label='dor0={}'.format(dor0[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.errorbar(np.arange(64),ERROR1[:,:,i].flatten(),yerr=ERROR1std[:,:,i].flatten(),label='Rytov={}'.format(Rytov[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.errorbar(np.arange(64),ERROR1[:,:,:,i].flatten(),yerr=ERROR1std[:,:,:,i].flatten(),label='H_HA={}'.format(H_HA[i]),ls='-',marker='o')
plt.legend()
plt.show()

ERROR1A = np.nansum(ERROR1/ERROR1std**2,axis=0)/np.nansum(1/ERROR1std**2,axis=0)
ERROR1AS = 1/np.nansum(1/ERROR1std**2,axis=0)**0.5
#plt.errorbar(np.arange(64),ERROR1A.flatten(),yerr=ERROR1AS.flatten())
for i in np.arange(4):
  plt.errorbar(np.arange(16),ERROR1A[i].flatten(),yerr=ERROR1AS[i].flatten(),label='r0={}'.format(r0[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.errorbar(np.arange(16),ERROR1A[:,i].flatten(),yerr=ERROR1AS[:,i].flatten(),label='Rytov={}'.format(Rytov[i]),ls='-',marker='o')
plt.legend()
plt.show()
for i in np.arange(4):
  plt.errorbar(np.arange(16),ERROR1A[:,:,i].flatten(),yerr=ERROR1AS[:,:,i].flatten(),label='H_HA={}'.format(H_HA[i]),ls='-',marker='o')
plt.legend()
plt.show()

ERROR1BA = np.sum(ERROR1A/ERROR1AS**2,axis=(0,1))/np.sum(1/ERROR1AS**2,axis=(0,1))
ERROR1BSA = 1/np.sum(1/ERROR1AS**2,axis=(0,1))**0.5
plt.errorbar(np.arange(4),ERROR1BA,yerr=ERROR1BSA,ls='-',marker='o',capsize=5,label='r0')
ERROR1BB = np.sum(ERROR1A/ERROR1AS**2,axis=(0,2))/np.sum(1/ERROR1AS**2,axis=(0,2))
ERROR1BSB = 1/np.sum(1/ERROR1AS**2,axis=(0,2))**0.5
plt.errorbar(np.arange(4),ERROR1BB,yerr=ERROR1BSB,ls='-',marker='o',capsize=5,label='Rytov')
ERROR1BC = np.sum(ERROR1A/ERROR1AS**2,axis=(1,2))/np.sum(1/ERROR1AS**2,axis=(1,2))
ERROR1BSC = 1/np.sum(1/ERROR1AS**2,axis=(1,2))**0.5
plt.errorbar(np.arange(4),ERROR1BC,yerr=ERROR1BSC,ls='-',marker='o',capsize=5,label='H_HA')
plt.legend()
plt.show()
print(ERROR1BA.max()-ERROR1BA.min(),ERROR1BB.max()-ERROR1BB.min(),ERROR1BC.max()-ERROR1BC.min())

plt.errorbar(dor0,dor0_contribution,dor0_contribution_s,marker='o',capsize=5)
plt.xlabel('dor0')
plt.ylabel('dor0 contribution to error (rad)')
plt.show()
plt.pcolor(r0,Rytov,ERROR1A.mean(-1))
plt.xlabel('r0')
plt.ylabel('Rytov')
plt.title('contribution in error after dor0 error reduction (rad)')
plt.colorbar()
plt.show()
plt.pcolor(r0,Rytov,np.mean(ERROR1AS**2,axis=-1)**0.5)
plt.xlabel('r0')
plt.ylabel('Rytov')
plt.title('contribution in error from H_HA (rad)')
plt.colorbar()
plt.show()