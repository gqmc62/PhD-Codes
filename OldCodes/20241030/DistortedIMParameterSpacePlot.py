# r0 is turbulence strength in line of sight

def angle_of_arrival(wvl,dact_immediate_dm,r0):
    alpha = np.sqrt(0.182 * wvl**2 * dact_immediate_dm**(-1./3.) * r0**(-5./3.))
    return alpha

def displacement(wvl,dact_immediate_dm,dact_next_immediate_dm,r0,z):
    displace = angle_of_arrival(wvl,dact_immediate_dm,r0) * z/dact_next_immediate_dm
    return displace

def rytov_number(wvl, r0, z):
    # calculate rytov number from rytov approximation
    k = 2.*np.pi/wvl                    # float; rad/m; Wave number.
    cn2dz = r02cn2(r0, wvl)        # float; Turbulence strength.
    variance_theory_approx = 0.563 * k**(7./6.) * cn2dz * z**(5./6.)
    return variance_theory_approx

def cn22r0(cn2dz,wvl=500e-9):
    r0 = (0.423*(2.*np.pi/wvl)**2*cn2dz)**(-3./5.)
    return r0

def r02cn2(r0,wvl=500e-9):
    cn2dz = r0**(-5./3.)/(0.423*(2.*np.pi/wvl)**2)
    return cn2dz

def rytov_contour_cn2_in_z_out(cn2dz,rytov,wvl):
    C1 = np.log10(0.563*(2.0*np.pi/wvl)**(7./6.))
    # C2 = 0.5*np.log10(0.182*0.423*(2.*np.pi)**2) - (1./6.)*np.log10(dact_immediate_dm) - np.log10(dact_next_immediate_dm)
    A = np.log10(rytov)
    P = np.log10(cn2dz)

    Q = (6./5.)*(A - C1 - P)
    z = 10.0**Q

    return z

def displacement_contour_cn2_in_z_out(cn2dz,displace,wvl,dact_immediate_dm,dact_next_immediate_dm):
    # C1 = np.log10(0.563*(2.0*np.pi/wvl)**(7./6.))
    C2 = 0.5*np.log10(0.182*0.423*(2.*np.pi)**2) - (1./6.)*np.log10(dact_immediate_dm) - np.log10(dact_next_immediate_dm)
    B = np.log10(displace)
    P = np.log10(cn2dz)

    Q = (B - C2 - 0.5*P)
    z = 10.0**Q

    return z

def rytov_contour_z_in_cn2_out(z,rytov,wvl):
    C1 = np.log10(0.563*(2.0*np.pi/wvl)**(7./6.))
    # C2 = 0.5*np.log10(0.182*0.423*(2.*np.pi)**2) - (1./6.)*np.log10(dact_immediate_dm) - np.log10(dact_next_immediate_dm)
    A = np.log10(rytov)
    #P = np.log10(cn2dz)
    Q = np.log10(z)

    #Q = (6./5.)*(A - C1 - P)
    #z = 10.0**Q
    P = A - C1 - (5./6.)*Q
    cn2dz = 10.0**P

    return cn2dz

def displacement_contour_z_in_cn2_out(z,displace,wvl,dact_immediate_dm,dact_next_immediate_dm):
    # C1 = np.log10(0.563*(2.0*np.pi/wvl)**(7./6.)) # log rytov
    C2 = 0.5*np.log10(0.182*0.423*(2.*np.pi)**2) - (1./6.)*np.log10(dact_immediate_dm) - np.log10(dact_next_immediate_dm) # log displacement
    B = np.log10(displace)
    #P = np.log10(cn2dz)
    Q = np.log10(z)

    #Q = (B - C2 - 0.5*P)
    #z = 10.0**Q
    P = 2.0*(B - C2 - Q)
    cn2dz = 10.0**P

    return cn2dz

def get_cndz_z_from_rytov_displace(wvl,dact_immediate_dm,dact_next_immediate_dm,rytov,displacement):


    A = np.log10(rytov)
    B = np.log10(displacement)
    C1 = np.log10(0.563*(2.0*np.pi/wvl)**(7./6.))
    C2 = 0.5*np.log10(0.182*0.423*(2.*np.pi)**2) - (1./6.)*np.log10(dact_immediate_dm) - np.log10(dact_next_immediate_dm)
    M = np.array([[   1., 5./6.],
                  [1./2.,    1.]])

    solve = np.linalg.inv(M) @ np.array([A - C1, B - C2])
    P = solve[0]
    Q = solve[1]

    cn2dz = 10.0**P
    z = 10.0**Q

    return cn2dz,z

def solve_quadratic(A,B,C):
    upper_root = (-B + np.sqrt(B**2 - 4.*A*C)) / (2.*A)
    lower_root = (-B - np.sqrt(B**2 - 4.*A*C)) / (2.*A)
    roots = [lower_root,upper_root]
    return roots
def low_angle_secz(zenith_angle,extra_height_to_turbulence_layer,distance_to_earth_centre=6378137.):
    # sec(zenith) / 'air mass' of the flat-earth believer model
    # but for round-earth believer model
    # should be as accurate as the earth can be perfectly round.
    # FYI earth is not round either
    R = np.float64(distance_to_earth_centre)
    H = np.float64(extra_height_to_turbulence_layer)
    Z = np.float64(zenith_angle) # in radians
    #print(R,H,Z)
    A = 1.
    B = 2.*R*np.cos(Z)
    C = -2.*R*H - H**2
    #print(A,B,C)
    roots = solve_quadratic(A,B,C)
    #print(roots)
    answer = np.max(roots)/(H)
    #print(answer)
    return answer

def give_z_from_rytov_etc(rytov,wvl,r0):

    k = 2.*np.pi/wvl                    # float; rad/m; Wave number.
    cn2dz = r02cn2(r0, wvl)        # float; Turbulence strength.
    z = rytov / ( 0.563 * k**(7./6.) * cn2dz ) ** (6./5.)
    return z

def give_z_from_displacement_etc(displacement,wvl,r0,dsubap):

    alpha = np.sqrt(0.182 * wvl**2 * dsubap**(-1./3.) * r0**(-5./3.))

    z = displacement / ( alpha / dsubap)

    return z



